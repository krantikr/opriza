"""What each mock business sells, who it sells to, and who supplies it.

Three businesses, three trades, so the agents are built against variety from
day one: a steel stockist (few big invoices in MT), a building-materials dealer
(many mid-size invoices in bags and pieces) and a pharma distributor (many
small invoices to chemists). Rates and costs are realistic for India in 2026
but invented; nothing here is real company data.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date


@dataclass(frozen=True)
class Item:
    key: str
    name: str
    group: str
    unit: str
    cost: float  # our buying rate per unit
    rate: float  # usual selling rate per unit
    gst: float  # percent
    share: float  # share of the trade's sales value
    qty: tuple[float, float]  # usual quantity on one invoice line
    aliases: tuple[str, ...] = ()
    hsn: str = ""


@dataclass(frozen=True)
class Supplier:
    name: str
    brand: str
    delta: float  # their price vs our usual cost, e.g. -0.01 = 1% cheaper
    days: int  # delivery days
    on_time: int  # percent of deliveries on time
    credit_days: int


@dataclass(frozen=True)
class Company:
    id: int
    slug: str
    name: str
    trade: str
    city: str
    areas: tuple[str, ...]
    annual_sales: float  # rupees
    avg_invoice: float  # rupees, before tax
    customers: int
    tally_version: str
    language: str
    owner: str
    team: tuple[tuple[str, str], ...]  # (name, role)
    items: tuple[Item, ...]
    suppliers: tuple[Supplier, ...]
    customer_kinds: tuple[str, ...]
    customer_stems: tuple[str, ...]
    credit_days: tuple[int, ...]
    seasonality: dict[int, float] = field(default_factory=dict)  # month -> multiplier


